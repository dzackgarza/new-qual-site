"""Generate BACKLOG.md: the measurement queues for outstanding corpus work.

Runs every named measurement tool and writes what it measured into
BACKLOG.md as a work queue. The file is a candidate list for someone to
read -- never a gate, and never an instruction to act. Authored
dispositions live in the issue tree (dzackgarza/new-qual-site#83).

    just backlog
    uv run python tools/backlog.py
"""

from __future__ import annotations

import argparse
from pathlib import Path

from qualc import audit, prose, provenance_hrefs
from qualc.card_completeness import check_card
from qualc.cli import load
from qualc.model import ParsedCard
from qualc.pandoc_batch import PandocServer
from qualc.unsolved import render as render_unsolved
from qualc.unsolved import unsolved

REPO = Path(__file__).resolve().parent.parent


def corpus_sections(
    root: Path,
) -> tuple[list[tuple[str, list[str]]], list[ParsedCard] | None]:
    """Audit-family checks over parsed cards, with full orphan id lists."""
    with PandocServer() as pandoc:
        parsed, wiki_pages, errors = load(root, pandoc)
    if errors:
        return [
            (
                "corpus-validation",
                [
                    f"corpus does not validate: {len(errors)} error(s); first: {errors[0]}"
                ],
            )
        ], None
    sections: list[tuple[str, list[str]]] = []
    for name, fn in audit.CHECKS.items():
        sections.append((name, fn(parsed).violations))
    sections.append(("orphans", sorted(audit.orphan_ids(parsed, wiki_pages, root))))
    return sections, parsed


def provenance_sections(root: Path) -> list[tuple[str, list[str]]]:
    return [
        (check.name, check.findings)
        for check in provenance_hrefs.run(provenance_hrefs.ALL, root=root)
    ]


def completeness_sections(root: Path) -> list[tuple[str, list[str]]]:
    findings: list[str] = []
    for path in sorted((root / "corpus").rglob("*.md")):
        issues = check_card(path)
        if issues:
            findings.append(f"{path.stem}: {', '.join(issues)}")
    return [("incomplete-metadata", findings)]


def render(sections: list[tuple[str, list[str]]]) -> str:
    lines = [
        "# Work queues (generated)",
        "",
        "Regenerated by `just backlog`. Measurements only — candidates to read, never a gate, never an instruction to act.",
        "Authored dispositions live in the [issue tree](https://github.com/dzackgarza/new-qual-site/issues/83).",
        "",
    ]
    for name, findings in sections:
        lines.append(f"## {name} ({len(findings)})")
        lines.append("")
        if findings:
            for finding in findings:
                lines.extend([f"- {finding}", ""])
        else:
            lines.extend(["ok", ""])
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--root", type=Path, default=REPO)
    parser.add_argument(
        "--with-queues",
        action="store_true",
        help=(
            "write the generated queues (unsolved cards, prose-only solutions) from the "
            "same parsed cards"
        ),
    )
    args = parser.parse_args(argv)
    root = args.root.resolve()
    corpus, parsed = corpus_sections(root)
    measured = None if parsed is None else prose.measure(parsed)
    if measured is not None:
        # The prose-only count rides in this report as a count, not as its list: the list
        # is Queue D, and a thousand-line second copy of it in this file would be a
        # ledger to keep right rather than a measurement.
        corpus += [
            (
                "prose-only-solutions",
                [
                    f"{len(measured)} of the {measured.with_solution} problem cards with a "
                    f"solution hold no numbered step; see {prose.QUEUE.as_posix()}"
                ],
            )
        ]
    sections = corpus + provenance_sections(root) + completeness_sections(root)
    rendered = render(sections)
    out = root / "BACKLOG.md"
    if out.exists() and out.read_text() == rendered:
        print("BACKLOG.md: up to date")
    else:
        out.write_text(rendered)
        total = sum(len(findings) for _name, findings in sections)
        print(f"BACKLOG.md: {len(sections)} queues, {total} finding(s)")
    if not args.with_queues:
        return
    if parsed is None or measured is None:
        raise SystemExit("corpus does not validate; the queues were not written")
    queues = {
        root / "queues" / "C-unsolved-cards.md": render_unsolved(unsolved(parsed)),
        root / prose.QUEUE: prose.render(measured),
    }
    for queue, text in queues.items():
        queue.parent.mkdir(parents=True, exist_ok=True)
        if queue.exists() and queue.read_text() == text:
            print(f"{queue.relative_to(root)}: up to date")
        else:
            queue.write_text(text)
            print(f"{queue.relative_to(root)}: rewritten")


if __name__ == "__main__":
    main()
